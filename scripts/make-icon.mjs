// Generates build/icon.ico (multi-resolution) and src/main/tray-icon.ts (a
// base64 tray image) from build/icon-source.png.
//
//   node scripts/make-icon.mjs
//
// Uses jimp (pure JS resize) + png-to-ico (ICO packing) — no native compiler.

import { Jimp } from 'jimp'
import pngToIco from 'png-to-ico'
import { writeFileSync, existsSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = resolve(root, 'build/icon-source.png')
const ICO_OUT = resolve(root, 'build/icon.ico')
const TRAY_OUT = resolve(root, 'src/main/tray-icon.ts')

const ICO_SIZES = [256, 128, 64, 48, 32, 16]
const TRAY_SIZE = 32

if (!existsSync(SOURCE)) {
  console.error(`\nMissing ${SOURCE}\nSave your icon PNG there (1024x1024 ideal), then re-run.\n`)
  process.exit(1)
}

async function pngBuffer(size) {
  const img = await Jimp.read(SOURCE)
  img.resize({ w: size, h: size })
  return img.getBuffer('image/png')
}

const icoBuffers = await Promise.all(ICO_SIZES.map(pngBuffer))
writeFileSync(ICO_OUT, await pngToIco(icoBuffers))
console.log(`✓ ${ICO_OUT}  (${ICO_SIZES.join(', ')} px)`)

const trayB64 = (await pngBuffer(TRAY_SIZE)).toString('base64')
writeFileSync(
  TRAY_OUT,
  `// AUTO-GENERATED by scripts/make-icon.mjs — do not edit by hand.\n` +
    `// Tray icon (${TRAY_SIZE}x${TRAY_SIZE}) embedded as a data URI.\n` +
    `export const TRAY_ICON_DATA_URI =\n  'data:image/png;base64,${trayB64}'\n`
)
console.log(`✓ ${TRAY_OUT}  (${TRAY_SIZE}px tray icon)`)
